"""The host-side motion contract, shared by different unchanged MCU protocols."""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from .models import PressCommand
from .serial_motion import MotionStatus, StopReport


@runtime_checkable
class MotionClient(Protocol):
    def connect(self) -> MotionStatus: ...
    def status(self) -> MotionStatus: ...
    def home(self) -> None: ...
    def move_to(self, x_mm: float, y_mm: float) -> None: ...
    def press(self, command: PressCommand) -> None: ...
    def request_stop(self) -> bool: ...
    def confirm_stop(self, *, stop_id: int | None = None) -> StopReport: ...
    def reset_stop(self) -> None: ...
    def link_not_ready_reason(self) -> str | None: ...
    def not_ready_reason(self) -> str | None: ...
